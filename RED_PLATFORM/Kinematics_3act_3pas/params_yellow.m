function p = params_yellow()
% Жёлтая платформа (геометрия из исходных OZK.m / PZK.m) в общем формате.
% Нужна для проверки: fk/ik_pose должны давать те же числа, что старый код.
%
% НУМЕРАЦИЯ: нога i соединяет нижний шарнир A_i с верхним B_i.
% Активные (с серво) ноги в этом механизме - 6, 2, 4; пассивные - 1, 3, 5.

% --- Основание ---
p.R_A   = 137;                                % радиус окружности нижних шарниров, мм
p.h_A   = 131;                                % высота осей серво / неподвижных точек, мм
p.A_ang = [15 105 135 225 255 -15];           % азимут точки A_i, град (i = 1..6)

% --- Звенья ---
p.active  = [6 2 4];   % порядок углов серво a = [a1 a2 a3] (как в PZK: C6, C2, C4)
p.passive = [1 3 5];
p.l_kr  = 40;          % кривошип (рычаг серво), мм
p.l_act = 150;         % тяга активной ноги, мм
p.l_pas = 200;         % пассивная SS-тяга, мм

% --- Кривошипы ---
% axis{i}: 'radial' - ось вала радиальна, 'tangential' - по касательной
% dir(i):  +1/-1 - в какую сторону кривошип уходит при положительном угле
% a_off:   сдвиг нуля (град): при a_off = 0 кривошип при угле 0 смотрит вверх
p.axis  = repmat({'radial'}, 1, 6);
p.dir   = ones(1,6);
p.a_off = [0 0 0];
p.a_ref  = [0 0 0];    % опорные углы для выбора сборки кривошипа в ОЗК (если branch пуст)
p.branch = [-1 -1 -1]; % сборка кривошипа: -1 - сторона, где лежит a = 0.
                       % Мёртвая точка у жёлтой платформы ~ +12.7° (см. test_yellow):
                       % при a выше неё нужна сборка +1.

% --- Платформа: шарниры в СК платформы (z = 0 - плоскость шарниров) ---
r = 112; Phi = 30*pi/180;
W = 2*r*sin(pi/3 - Phi/2) + 4*r*sin(Phi/2);
K = r*sin(Phi/2)/(2*r*sin(Phi/2) + r*sin(pi/3 - Phi/2));
Rw = W/sqrt(3);
W1 = [Rw; 0; 0]; W2 = [Rw*cosd(120); Rw*sind(120); 0]; W3 = [Rw*cosd(240); Rw*sind(240); 0];
p.Bp = [W1+K*(W3-W1), W1+K*(W2-W1), W2+K*(W1-W2), W2+K*(W3-W2), W3+K*(W2-W3), W3+K*(W1-W3)];

p.z_off = 21;          % выходное звено VZ выше плоскости шарниров на 21 мм (по оси z платформы)

% --- Нейтральная поза (все серво = 0) ---
p = neutralPose(p, [311.6 68.7]);
end
