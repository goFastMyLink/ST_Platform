function p = params_3servo()
% Платформа с 3 серво FEETECH FB5118M (PCA9685) + 3 пассивные SS-тяги.
%
% Основание, кривошипы и тяги - ЗАМЕРЕНЫ (30.09.2026).
% Верхняя платформа - замерена. z_off (высота выходной точки) - пока 0.
%
% НУМЕРАЦИЯ по схеме (в коде A_i - нижние шарниры B_i со схемы, B_i - верхние b_i):
%   основание: пары (A6,A1), (A2,A3), (A4,A5), против часовой, пара (6,1) - на оси X0;
%   платформа: пары (B1,B2), (B3,B4), (B5,B6), сдвинуты на 60° относительно нижних.
%   Нога i: A_i -> B_i, поэтому ноги из соседних нижних пар сходятся в одну верхнюю.
%   Серво стоят в A1, A3, A5 (активные RSS-ноги).
%   A6, A2, A4 - неподвижные точки, тяга - SS фиксированной длины.

% --- Основание ---
% Замеры: ось вала серво радиальна, кривошип при угле 0 горизонтален и смотрит
% по касательной. Оси валов (A1, A3, A5) и неподвижные точки (A6, A2, A4) - на радиусе 140 мм.
p.l_kr = 40;                 % кривошип: от оси вала до центра шара, мм (замерено)
p.R_A  = 140;                % радиус осей серво и неподвижных точек, мм (замерено)
                             % (можно задать и [1x6], если радиусы у ног разные)
p.h_A = 130;                 % высота оси вала / неподвижных точек над основанием, мм (замерено)
cA = [0 120 240];            % азимуты центров пар (6,1), (2,3), (4,5), град (по схеме X0 - на паре 6,1)
d_pair = 70;                 % расстояние ось серво <-> неподвижная точка в паре, мм (замерено)
sA = 2*asind(d_pair/2/p.R_A);% тот же разнос в градусах (~28.96°)
% Нумерация A1..A6 идёт по кругу против часовой стрелки: A6|A1, A2|A3, A4|A5.
% Серво (A1, A3, A5) - в каждой паре точка с БОЛЬШИМ азимутом.
p.A_ang = [cA(1)+sA/2, cA(2)-sA/2, cA(2)+sA/2, cA(3)-sA/2, cA(3)+sA/2, cA(1)-sA/2];

% --- Звенья ---
p.active  = [1 3 5];         % порядок углов серво a = [a1 a2 a3] = серво в A1, A3, A5
p.passive = [6 2 4];
p.l_act = 165;               % активная тяга, между центрами шаров, мм (замерено)
p.l_pas = 205;               % пассивная тяга, между центрами шаров, мм (замерено)

% --- Кривошипы ---
p.axis  = repmat({'radial'}, 1, 6);  % ось вала радиальна, кривошип качается по касательной (замерено)
p.dir   = -ones(1,6);                % при угле 0 кривошип смотрит от неподвижной точки пары,
                                     % т.е. против часовой (-1). Знак +угла проверить на стенде
p.a_off = [90 90 90];                % 90 -> при угле серво 0 кривошип горизонтален
p.a_ref = [0 0 0];
p.branch = [];               % после замеров: задать [+-1 +-1 +-1] по test_3servo

% --- Платформа: шарниры в СК платформы, z = 0 - плоскость центров шаров ---
r_B = 100;                   % радиус окружности центров верхних шаров, мм (замерено)
cB  = [60 180 300];          % центры пар (1,2), (3,4), (5,6) - посередине между нижними парами (по схеме)
d_pairB = 55;                % расстояние между шарами в верхней паре (b1-b2), мм (замерено)
sB  = 2*asind(d_pairB/2/r_B);
%         B1          B2          B3          B4          B5          B6
B_ang = [cB(1)-sB/2, cB(1)+sB/2, cB(2)-sB/2, cB(2)+sB/2, cB(3)-sB/2, cB(3)+sB/2];
p.Bp = [r_B*cosd(B_ang); r_B*sind(B_ang); zeros(1,6)];

p.z_off = 0;                 % [ЗАМЕРИТЬ] расстояние от плоскости шарниров до точки,
                             % которую считаем выходом (например, центр MPU), мм

% --- Нейтральная поза: грубая оценка высоты и рыскания, дальше уточнит fsolve ---
p = neutralPose(p, [p.h_A + p.l_act, -30]);
end
