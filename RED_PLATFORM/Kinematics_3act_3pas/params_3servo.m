function p = params_3servo()
% Платформа с 3 серво FEETECH FB5118M (PCA9685) + 3 пассивные SS-тяги.
%
% !!! ВСЕ ЧИСЛА НИЖЕ - ЗАГЛУШКИ. Замерь реальную конструкцию и подставь. !!!
% Пока стоят заглушки, код запускается, но считает НЕ твою платформу.
%
% НУМЕРАЦИЯ (как мы разбирали): пары на основании A1(A6), A2(A3), A4(A5),
% на платформе B1(B6), B2(B3), B4(B5). Нога i: A_i -> B_i.
%   Серво стоят в A1, A3, A5 (активные RSS-ноги).
%   A6, A2, A4 - неподвижные точки, тяга - SS фиксированной длины.

% --- Основание ---
p.R_A = 100;                 % [ЗАМЕРИТЬ] радиус окружности осей серво / неподвижных точек, мм
p.h_A = 20;                  % [ЗАМЕРИТЬ] высота этих точек над началом ГСК, мм
cA = [90 210 330];           % [ЗАМЕРИТЬ] азимуты центров пар (1,6), (2,3), (4,5), град
sA = 20;                     % [ЗАМЕРИТЬ] угловой разнос точек внутри пары, град
%               A1          A2          A3          A4          A5          A6
p.A_ang = [cA(1)-sA/2, cA(2)-sA/2, cA(2)+sA/2, cA(3)-sA/2, cA(3)+sA/2, cA(1)+sA/2];

% --- Звенья ---
p.active  = [1 3 5];         % порядок углов серво a = [a1 a2 a3] = серво в A1, A3, A5
p.passive = [6 2 4];
p.l_kr  = 25;                % [ЗАМЕРИТЬ] кривошип: от оси вала до центра шара, мм
p.l_act = 130;               % [ЗАМЕРИТЬ] активная тяга, между центрами шаров, мм
p.l_pas = 130;               % [ЗАМЕРИТЬ] пассивная тяга, между центрами шаров, мм

% --- Кривошипы ---
p.axis  = repmat({'radial'}, 1, 6);  % [ПРОВЕРИТЬ] ось вала серво: 'radial' или 'tangential'
p.dir   = [1 1 1 1 1 1];             % [ПРОВЕРИТЬ] знак: куда уходит кривошип при +угле
p.a_off = [90 90 90];                % 90 -> при угле серво 0 кривошип горизонтален
p.a_ref = [0 0 0];
p.branch = [];               % после замеров: задать [+-1 +-1 +-1] по test_3servo

% --- Платформа: шарниры в СК платформы, z = 0 - плоскость центров шаров ---
r_B = 60;                    % [ЗАМЕРИТЬ] радиус окружности верхних шарниров, мм
cB  = cA;                    % [ЗАМЕРИТЬ] азимуты центров пар B1(B6), B2(B3), B4(B5)
sB  = 20;                    % [ЗАМЕРИТЬ] разнос внутри пары, град
B_ang = [cB(1)-sB/2, cB(2)-sB/2, cB(2)+sB/2, cB(3)-sB/2, cB(3)+sB/2, cB(1)+sB/2];
p.Bp = [r_B*cosd(B_ang); r_B*sind(B_ang); zeros(1,6)];

p.z_off = 0;                 % [ЗАМЕРИТЬ] расстояние от плоскости шарниров до точки,
                             % которую считаем выходом (например, центр MPU), мм

% --- Нейтральная поза: грубая оценка высоты и рыскания, дальше уточнит fsolve ---
p = neutralPose(p, [p.h_A + p.l_act, 0]);
end
