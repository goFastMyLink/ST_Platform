function [P0, u, v] = crankGeom(p, i)
% Геометрия кривошипа активной ноги i:
%   P0 - ось вала серво (центр вращения кривошипа) в ГСК
%   u  - направление кривошипа при математическом угле 0
%   v  - направление кривошипа при математическом угле +90°
% Конец кривошипа: C(a) = P0 + l_kr*( cos(a+off)*u + sin(a+off)*v )
g  = p.A_ang(i)*pi/180;
P0 = [p.R_A*cos(g); p.R_A*sin(g); p.h_A];
er = [cos(g); sin(g); 0];            % радиальное направление
et = [-sin(g); cos(g); 0];           % касательное (против часовой)
ez = [0; 0; 1];
switch p.axis{i}
    case 'radial'      % ось вала радиальна -> кривошип качается в касательно-вертикальной плоскости
        h = et;
    case 'tangential'  % ось вала по касательной -> кривошип качается в радиально-вертикальной плоскости
        h = er;
    otherwise
        error('p.axis{%d} должно быть ''radial'' или ''tangential''', i);
end
u = ez;
v = -p.dir(i)*h;
end
